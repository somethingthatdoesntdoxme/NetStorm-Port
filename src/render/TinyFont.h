#pragma once
// Minimal 5x7 bitmap font for HUD text until the original .chfnt fonts are
// decoded. Upper-case letters, digits and a little punctuation.
#include <SDL.h>

#include <cctype>
#include <string>

namespace ns {

inline const uint8_t* tinyGlyph(char c) {
  static const uint8_t font[][7] = {
      {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 0 1
      {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 2 3
      {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 4 5
      {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 6 7
      {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},  // 8 9
      {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},  // A B
      {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}, {0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C},  // C D
      {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}, {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},  // E F
      {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F}, {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // G H
      {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E}, {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C},  // I J
      {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},  // K L
      {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, {0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11},  // M N
      {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},  // O P
      {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D}, {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},  // Q R
      {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},  // S T
      {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},  // U V
      {0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A}, {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},  // W X
      {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}, {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},  // Y Z
      {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C}, {0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00},  // . :
      {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00}, {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10},  // - /
      {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02}, {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08},  // ( )
      {0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00}, {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},  // + space
  };
  c = char(std::toupper(static_cast<unsigned char>(c)));
  if (c >= '0' && c <= '9') return font[c - '0'];
  if (c >= 'A' && c <= 'Z') return font[10 + c - 'A'];
  switch (c) {
    case '.': return font[36];
    case ':': return font[37];
    case '-': return font[38];
    case '/': return font[39];
    case '(': return font[40];
    case ')': return font[41];
    case '+': return font[42];
    default: return font[43];
  }
}

// Draws text with a 1px drop shadow. Returns the width in pixels.
inline float drawText(SDL_Renderer* r, float x, float y, float scale, const std::string& s, SDL_Color col) {
  for (int pass = 0; pass < 2; ++pass) {
    float off = pass == 0 ? scale : 0;
    SDL_Color c = pass == 0 ? SDL_Color{0, 0, 0, 200} : col;
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    float cx = x;
    for (char ch : s) {
      const uint8_t* g = tinyGlyph(ch);
      for (int row = 0; row < 7; ++row)
        for (int bit = 0; bit < 5; ++bit)
          if (g[row] & (0x10 >> bit)) {
            SDL_FRect px{cx + bit * scale + off, y + row * scale + off, scale, scale};
            SDL_RenderFillRectF(r, &px);
          }
      cx += 6 * scale;
    }
  }
  return float(s.size()) * 6 * scale;
}

}  // namespace ns
